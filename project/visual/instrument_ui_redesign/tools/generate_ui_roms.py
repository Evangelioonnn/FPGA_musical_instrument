"""Offline preparation of finite Chinese/ASCII glyphs and HDL text ROMs.
The running FPGA uses only the generated ROMs. No runtime PC/font dependency.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import argparse, hashlib, json

p=argparse.ArgumentParser()
p.add_argument('--font',default='C:/Windows/Fonts/msyh.ttc')
args=p.parse_args()
root=Path(__file__).resolve().parents[1]
out=root/'src/rtl'
out.mkdir(parents=True,exist_ok=True)
rows={
 1:[(2,'我的曲库'),(12,'演奏'),(21,'音色编辑'),(34,'声音分析'),(47,'设置')],
 3:[(2,'演奏主屏'),(43,'实时音频V2')],
 6:[(4,'谐波钢琴'),(42,'数字增益')],7:[(48,'%')],
 8:[(4,'温暖拨弦')],10:[(4,'金属铃'),(42,'房间混合')],11:[(47,'%')],
 12:[(4,'驱动Lead')],14:[(4,'自定义四谐波'),(42,'声部'),(50,'/32'),(56,'/12')],
 16:[(29,'原始码HEX')],
 18:[(4,'音量'),(15,'普通延音'),(28,'选择延音'),(41,'释放'),(50,'房间')],
 19:[(7,'%')],20:[(41,'档位')],
 22:[(4,'左区MIDI'),(28,'右区MIDI')],
 23:[(2,'25键显示/16键输入'),(42,'状态序号')],
 24:[(2,'H按住 S延音 R释放'),(41,'削波'),(50,'期限')],
}
modes=['主音量','左区八度','右区八度','释放档位','滑入档位','弯音档位','Lead起音','颤音深度','颤音速度','房间开关','房间混合','ADSR起音','ADSR衰减','ADSR保持','ADSR释放','ADSR覆盖','持续模式','未使用','谐波一','谐波二','谐波三','谐波四']
presets={0:'谐波钢琴',2:'温暖拨弦',3:'金属铃',4:'驱动Lead',5:'自定义四谐波'}
wave_rows={
 1:[(2,'演奏主屏'),(14,'声音分析'),(29,'实时波形')],
 3:[(2,'实时双声道波形')],
 5:[(3,'L 左声道'),(44,'连续采样窗口')],
 6:[(2,'+V'),(44,'512 PCM')],8:[(44,'PEAK 0x')],12:[(44,'SCOPE AUTO V2')],10:[(3,'0'),(44,'10.65 ms')],13:[(2,'-V')],
 16:[(3,'R 右声道'),(44,'Fs 48076.92 Hz')],
 17:[(2,'+V')],21:[(3,'0'),(44,'AUTO x2^ ')],24:[(2,'-V')],
 27:[(8,'0'),(16,'2.66'),(24,'5.32'),(32,'7.99'),(40,'10.65 ms')],
 30:[(3,'长按音色键切换页面'),(34,'短按音色键切换音色')],
}
texts=[s for pairs in rows.values() for _,s in pairs]+modes+list(presets.values())+[s for pairs in wave_rows.values() for _,s in pairs]
texts+=['全幅 / 线性']
chinese=sorted({c for s in texts for c in s if ord(c)>127})
assert len(chinese)<=128
mapping={c:i+128 for i,c in enumerate(chinese)}
def code(c):return mapping[c] if c in mapping else ord(c)
font_file=Path(args.font)
font=ImageFont.truetype(str(font_file),16)
ascii_font=ImageFont.truetype(str(font_file),15)
font_data=[0]*4096
for c in ''.join(chr(i) for i in range(32,127))+''.join(chinese):
    f=font if ord(c)>127 else ascii_font
    image=Image.new('1',(16,16))
    d=ImageDraw.Draw(image)
    box=d.textbbox((0,0),c,font=f)
    d.text(((16-(box[2]-box[0]))//2-box[0],-box[1]),c,font=f,fill=1)
    for y in range(16):
        font_data[code(c)*16+y]=sum((1<<(15-x)) for x in range(16) if image.getpixel((x,y)))
labels=[32]*4096
for row,pairs in rows.items():
    for col,text in pairs:
        assert col+len(text)<=60
        labels[row*64+col:row*64+col+len(text)]=[code(c) for c in text]
for i,text in enumerate(modes):labels[2048+i*32:2048+i*32+len(text)]=[code(c) for c in text]
for i,text in presets.items():labels[3072+i*32:3072+i*32+len(text)]=[code(c) for c in text]
def emit(name,width,aw,data):
    lines=['// Generated by tools/generate_ui_roms.py; edit that generator.',
           f'module {name}(input wire clk,input wire [{aw-1}:0] address,output reg [{width-1}:0] data);',
           f'(* syn_ramstyle="block_ram" *) reg [{width-1}:0] rom[0:{len(data)-1}];','initial begin']
    lines += [f"rom[{i}]={width}'d{v};" for i,v in enumerate(data)]
    lines += ['end','always @(posedge clk) data<=rom[address];','endmodule','']
    (out/(name+'.v')).write_text('\n'.join(lines),encoding='ascii')
emit('av_font',16,12,font_data)
emit('av_labels',8,12,labels)
wave_labels=[32]*2048
for row,pairs in wave_rows.items():
    for col,text in pairs:
        assert col+len(text)<=60
        wave_labels[row*64+col:row*64+col+len(text)]=[code(c) for c in text]
emit('av_wave_labels',8,11,wave_labels)
validation=root/'validation';validation.mkdir(exist_ok=True)
(validation/'font_source.json').write_text(json.dumps({'offline_font':font_file.name,'sha256':hashlib.sha256(font_file.read_bytes()).hexdigest(),'chinese_glyphs':len(chinese),'character_codes':mapping,'runtime':'Generated HDL ROM only; no font package or PC required.'},ensure_ascii=False,indent=2),encoding='utf8')
print(f'Generated {len(chinese)} Chinese glyphs; 16x16 ROM and text labels.')
