"""Generate mathematical delay/mean tables. No recorded instrument samples."""
from pathlib import Path
import math

FS = 50_000_000 / 1040
OUT = Path(__file__).resolve().parents[1] / 'src/pluck_note_table.v'
lines = ['// Generated by ../tools/generate_tables.py; Fs=50MHz/1040.',
         'module pluck_note_table(input wire [6:0] note,',
         '    output reg [9:0] length, output reg [15:0] fraction,',
         '    output reg [24:0] reciprocal);', 'always @* begin', '    case(note)']
for note in range(36, 85):
    delay = FS / (440 * 2 ** ((note - 69) / 12)) - .5
    integer = math.floor(delay)
    frac = round((delay - integer) * 65536)
    if frac == 65536:
        integer += 1
        frac = 0
    length = integer + 2
    reciprocal = round(2 ** 24 / length)
    lines.append(f"        7'd{note}: begin length=10'd{length}; fraction=16'd{frac}; reciprocal=25'd{reciprocal}; end")
lines += ["        default: begin length=10'd185; fraction=16'd0; reciprocal=25'd90688; end",
          '    endcase', 'end', 'endmodule', '']
OUT.write_text('\n'.join(lines), encoding='utf-8')
print(OUT)
